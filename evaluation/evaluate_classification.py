def load_label_info(json_path: str) -> Tuple[List[str], List[str], List[Dict[str, str]]]:
    
    """
    Load labels, descriptions, and few-shot examples from a JSON file.

    Args:
        json_path (str): Path to the JSON file containing label information.

    Returns:
        Tuple[List[str], List[str], List[Dict[str, str]]]: A tuple containing lists of labels,
        their descriptions, and few-shot examples for each label.
    """
    
    with open(json_path) as f:
        label_data = json.load(f)

    labels = list(label_data["labels"].keys())
    descriptions = [label_data["labels"][label]["description"] for label in labels]
    few_shot_examples = [
                            {"text": example, "label": label}
                            for label, info in label_data["labels"].items()
                            for example in info.get("example", [])
                        ]
    
    return labels, descriptions, few_shot_examples

# ======================================================================================================================================== #

def evaluate_predictions(task_type: str, true_labels: List[Any], predicted_labels: List[Any]) -> Dict[str, float]:
    
    """
    Evaluate predictions using the appropriate metrics based on task type.

    Args:
        task_type (str): Type of classification task (binary, multi-class, multi-label).
        true_labels (List[Any]): True labels for the dataset.
        predicted_labels (List[Any]): Predicted labels generated by the model.

    Returns:
        Dict[str, float]: A dictionary containing calculated metrics.
    """
    
    metrics = {}

    if task_type == "binary" or task_type == "multi-class":
        accuracy = accuracy_score(true_labels, predicted_labels)
        precision = precision_score(true_labels, predicted_labels, average="macro", zero_division=1)
        recall = recall_score(true_labels, predicted_labels, average="macro", zero_division=1)
        f1 = f1_score(true_labels, predicted_labels, average="macro", zero_division=1)
        metrics.update({"accuracy": accuracy, "precision": precision, "recall": recall, "f1": f1})
        
        #### Future work: add additional metrics 
#         conf_matrix = confusion_matrix(y_true, y_pred)
#         class_report = classification_report(y_true, y_pred, zero_division=1)
#         balanced_accuracy = balanced_accuracy_score(y_true, y_pred)
#         metrics.update({"confusion matrix": conf_matrix, "classification report": class_report, "class balanced accuracy": balanced_accuracy})
        
    elif task_type == "multi-label":  ## Future work:support multi-label classification
        hamming = hamming_loss(true_labels, predicted_labels)
        avg_precision = average_precision_score(true_labels, predicted_labels, average="samples")
        ranking_avg_precision = label_ranking_average_precision_score(true_labels, predicted_labels)
        metrics.update({"hamming_loss": hamming, "average_precision": avg_precision, "label_ranking_average_precision": ranking_avg_precision})

    return metrics

# ======================================================================================================================================== #

def process_dataset(config: Dict[str, Any]) -> Dict[str, float]:
    
    """
    Process a single dataset and compute evaluation metrics.

    Args:
        config (Dict[str, Any]): Configuration dictionary containing dataset paths, task type, and other parameters.

    Returns:
        Dict[str, float]: A dictionary of evaluation metrics for the dataset.
    """
    
    # Load the CSV and JSON configuration
    data = pd.read_csv(config["csv_path"])
    labels, descriptions, few_shot_examples = load_label_info(config["json_path"])

    true_labels = []
    predicted_labels = []
    
    # Process each row in the dataset
    for _, row in data.iterrows():
        text = row["text"]
        true_label = row["true_label"] if config["task_type"] != "multi-label" else json.loads(row["true_label"])  # Handle multi-label as list
        
        # Prepare payload for API request, including multi_label flag
        payload = {
            "text": text,
            "labels": labels,
            "descriptions": descriptions,
            "few_shot_examples": few_shot_examples,
            "is_multi_label": config.get("multi_label", False)  # Add multi_label flag from config
        }

        # Send request to API
        response = requests.post(api_url, json=payload)
        if response.status_code == 200:
            predicted_label = response.json()["label"]
            # For multi-label, we assume the response returns a list of labels
            predicted_label = json.loads(predicted_label) if config.get("multi_label", False) else predicted_label
        else:
            print(f"Error with request: {response.status_code}, {response.text}")
            predicted_label = None

        # Collect true and predicted labels
        true_labels.append(true_label.strip().lower())
        predicted_labels.append(predicted_label.strip().lower())
        

    results_dir = "results"
    os.makedirs(results_dir, exist_ok=True)
    result_path = f"results/{config["dataset_name"]}_prediction.json"
    with open(result_path, "w") as f:
        json.dump(predicted_labels, f, indent=4)
        
    # Calculate metrics for the dataset
    metrics = evaluate_predictions(config["task_type"], true_labels, predicted_labels)
    
    return metrics

# ======================================================================================================================================== #

def main():
    
    """Main function to process each dataset and save evaluation metrics."""
    
    results_dir = "results"
    os.makedirs(results_dir, exist_ok=True)

    for dataset_name, config in dataset_config.items():
        print(f"Processing {dataset_name} dataset...")
        metrics = process_dataset(config)
        
        # Save results in a JSON file based on task type
        result_path = os.path.join(results_dir, f"{config['dataset_name']}_report.json")
        with open(result_path, "w") as f:
            json.dump(metrics, f, indent=4)
        print(f"Metrics for {dataset_name} dataset saved to {result_path}")

        
# ======================================================================================================================================== #
        
if __name__ == "__main__":
    main()
